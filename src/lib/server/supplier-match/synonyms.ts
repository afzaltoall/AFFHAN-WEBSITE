const escapeRe = (s: string) => s.replace(/[.*+?^$()|[\]\\{}]/g, "\\$&");

/** A term's variants: itself, then itself with one listed phrase replaced by each of its alternatives. */
export function variantsOf(term: string): string[] {
  const out = new Set([term]);
  for (const [phrase, alternatives] of SYNONYMS) {
    const re = new RegExp(`(^|\\s)${escapeRe(phrase)}(?=\\s|$)`);
    if (!re.test(term)) continue;
    for (const alt of alternatives) out.add(term.replace(re, `$1${alt}`).trim());
  }
  return [...out];
}
